#pragma pack(push, 1)
struct TModemHeader
{
    quint8 sync1;
    quint8 sync2;
    quint8 route;
    quint8 command;
    quint8 sn;
    quint16 length = 0;   // payload 长度(低12位) + 压缩标志等(高4位)
    quint8 xorChk = 0;    // header的异或校验

    // -- route 操作 --
    quint8 getDevAddr() const { return route & 0x0F; } //获取route的低4位  设备地址
    quint8 getVersion() const { return (route >> 4) & 0x03; } //取第4、5位   通讯协议版本号0、1、2、3
    bool getNeedAck() const   { return route & 0x40; } //取第6位   ACK请求
    bool getAckMark() const   { return route & 0x80; }

    void setDevAddr(quint8 val) { route = (route & 0xF0) | (val & 0x0F); }
    void setVersion(quint8 val) { route = (route & 0xCF) | ((val & 0x03) << 4); }
    void setNeedAck(bool v)     { route = v ? (route | 0x40) : (route & ~0x40); }
    void setAckMark(bool v)     { route = v ? (route | 0x80) : (route & ~0x80); }

    // -- command 操作 --
    quint8 getSubCommand() const { return command & 0x0F; }
    quint8 getCommand() const    { return (command >> 4) & 0x0F; }

    void setSubCommand(quint8 val) { command = (command & 0xF0) | (val & 0x0F); }
    void setCommand(quint8 val)    { command = (command & 0x0F) | ((val & 0x0F) << 4); }

    // -- length 操作 --
    quint16 getLength() const { return length & 0x0FFF; }
    quint8 getLength_L() const { return static_cast<quint8>(length & 0xFF); }
    quint8 getLength_H() const { return static_cast<quint8>((length >> 8) & 0xFF); }
    quint8 getReserved() const { return (length >> 12) & 0x03; }
    quint8 getCompress() const { return (length >> 14) & 0x03; }

    void setLength(quint16 len) { length = (length & 0xF000) | (len & 0x0FFF); }
    void setLength_L(quint8 val) { length = (length & 0xFF00) | val; }
    void setLength_H(quint8 val) { length = (length & 0x00FF) | (static_cast<quint16>(val) << 8); }
    void setReserved(quint8 val) { length = (length & 0xCFFF) | ((val & 0x03) << 12); }
    void setCompress(quint8 val) { length = (length & 0x3FFF) | ((val & 0x03) << 14); }

#if 1
    // 改成crc8计算
    quint8 calcXorChk() const {
        const uint8_t* p = reinterpret_cast<const uint8_t*>(this);
        uint8_t crc = 0;
        for (size_t i = 0; i < sizeof(TModemHeader) - 1; ++i)  // 不包括最后的crc字节
        {
            crc = crc8_table[crc ^ p[i]];
        }
        return crc;
    }

#else
    // 新增：计算 xorChk（不含自身）
    quint8 calcXorChk() const {
        const quint8* p = reinterpret_cast<const quint8*>(this);
        quint8 xorv = 0;
        //qDebug() << "XOR input bytes:";
        for (size_t i = 0; i < sizeof(StructHeaderTBBP) - 1; ++i) {
            //qDebug() << QString("%1").arg(p[i], 2, 16, QLatin1Char('0'));
            xorv ^= p[i];
        }
        //qDebug() << "XOR result:" << QString("0x%1").arg(xorv, 2, 16, QLatin1Char('0'));
        return xorv;
    }
#endif
    bool verifyXorChk() const {
        return xorChk == calcXorChk();
    }

    void updateXorChk() {
        xorChk = calcXorChk();
    }

};
#pragma pack(pop)



