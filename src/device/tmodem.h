struct StructFrameTM
{
    TModemHeader header;
    QByteArray payload;
    quint8 check1 = 0;
    quint8 check2 = 0;

    // 设置 payload 并更新 header.length
    void setPayload(const QByteArray &data)
    {
        payload = data;
        header.setLength(static_cast<quint16>(data.size()));
    }

    // 构造完整帧（用于发送）
    QByteArray toByteArray() const
    {
        QByteArray buf;
        buf.append(reinterpret_cast<const char*>(&header), sizeof(TModemHeader));
        buf.append(payload);
        buf.append(check1);
        buf.append(check2);
        return buf;
    }

    // 解析原始数据
    bool fromByteArray(const QByteArray &raw)
    {
        if (raw.size() < sizeof(TModemHeader) + 2)
            return false;

        memcpy(&header, raw.constData(), sizeof(TModemHeader));
        int payloadLen = header.getLength();
        if (raw.size() < sizeof(TModemHeader) + payloadLen + 2)
            return false;

        payload = raw.mid(sizeof(TModemHeader), payloadLen);
        check1 = static_cast<quint8>(raw.at(sizeof(TModemHeader) + payloadLen));
        check2 = static_cast<quint8>(raw.at(sizeof(TModemHeader) + payloadLen + 1));
        return true;
    }

#if 1
    // 计算 CRC16 (header + payload)，不含 check1/check2
    uint16_t calcCrc16() const
    {
        uint16_t crc = 0xFFFF; // Modbus CRC初值，一般是0xFFFF
        const uint8_t* data = reinterpret_cast<const uint8_t*>(&header);
        int len = sizeof(TModemHeader);
        for (int i = 0; i < len; ++i)
        {
            crc = (crc >> 8) ^ crc16_modbus_table[(crc ^ data[i]) & 0xFF];
        }

        for (auto b : payload)
        {
            crc = (crc >> 8) ^ crc16_modbus_table[(crc ^ static_cast<uint8_t>(b)) & 0xFF];
        }

        return crc;
    }

    void updateChecks()
    {
        header.updateXorChk(); // 如果头部用crc8的话，先更新头部CRC8

        uint16_t crc = calcCrc16();
        check1 = static_cast<quint8>(crc & 0xFF);        // 低字节
        check2 = static_cast<quint8>((crc >> 8) & 0xFF); // 高字节
    }

    bool verifyChecks() const
    {
        uint16_t crc = calcCrc16();
        return (check1 == static_cast<quint8>(crc & 0xFF)) &&
               (check2 == static_cast<quint8>((crc >> 8) & 0xFF));
    }
#else
    // 计算 check1/check2
    void calcChecks(quint8 &c1, quint8 &c2) const
    {
        QByteArray buf;
        buf.append(reinterpret_cast<const char*>(&header), sizeof(StructHeaderTBBP));
        buf.append(payload);
        c1 = c2 = 0;
        for (auto b : buf)
        {
            c1 += static_cast<quint8>(b);
            c2 += c1;
        }
    }

    void updateChecks()
    {
        header.updateXorChk(); // <== 先更新头部校验
        calcChecks(check1, check2);
    }

    bool verifyChecks() const
    {
        quint8 c1, c2;
        calcChecks(c1, c2);
        return (check1 == c1) && (check2 == c2);
    }
#endif
};





